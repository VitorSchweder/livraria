BEGIN;

-- -----------------------------------------------------------------------------
-- Livro (modelo original + campo valor)
-- -----------------------------------------------------------------------------
CREATE TABLE livro (
    codl          INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulo        VARCHAR(40)    NOT NULL,
    editora       VARCHAR(40)    NOT NULL,
    edicao        INT            NOT NULL,
    anopublicacao VARCHAR(4)     NOT NULL,
    valor         NUMERIC(10, 2) NOT NULL,
    PRIMARY KEY (codl),
    CONSTRAINT livro_edicao_chk        CHECK (edicao > 0),
    CONSTRAINT livro_anopublicacao_chk CHECK (anopublicacao ~ '^[0-9]{4}$'),
    CONSTRAINT livro_valor_chk         CHECK (valor >= 0)
);
CREATE INDEX livro_titulo_idx ON livro (titulo);

-- -----------------------------------------------------------------------------
-- Autor
-- -----------------------------------------------------------------------------
CREATE TABLE autor (
    codau INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome  VARCHAR(40) NOT NULL,
    PRIMARY KEY (codau)
);
CREATE INDEX autor_nome_idx ON autor (nome);

-- -----------------------------------------------------------------------------
-- Assunto
-- -----------------------------------------------------------------------------
CREATE TABLE assunto (
    codas     INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    descricao VARCHAR(20) NOT NULL,
    PRIMARY KEY (codas)
);
CREATE UNIQUE INDEX assunto_descricao_uniq ON assunto (descricao);

-- -----------------------------------------------------------------------------
-- Livro_Autor (Rel_01 / Rel_02)
-- Excluir um livro remove seus vínculos (CASCADE); um autor vinculado não pode
-- ser excluído (RESTRICT).
-- -----------------------------------------------------------------------------
CREATE TABLE livro_autor (
    livro_codl  INT NOT NULL,
    autor_codau INT NOT NULL,
    PRIMARY KEY (livro_codl, autor_codau)
);
CREATE INDEX IDX_6749992A53550D7 ON livro_autor (livro_codl);   -- Livro_Autor_FKIndex1
CREATE INDEX IDX_67499926696BB47 ON livro_autor (autor_codau);  -- Livro_Autor_FKIndex2
ALTER TABLE livro_autor ADD CONSTRAINT FK_6749992A53550D7
    FOREIGN KEY (livro_codl) REFERENCES livro (codl) ON DELETE CASCADE NOT DEFERRABLE;
ALTER TABLE livro_autor ADD CONSTRAINT FK_67499926696BB47
    FOREIGN KEY (autor_codau) REFERENCES autor (codau) ON DELETE RESTRICT NOT DEFERRABLE;

-- -----------------------------------------------------------------------------
-- Livro_Assunto (Rel_03 / Rel_04)
-- -----------------------------------------------------------------------------
CREATE TABLE livro_assunto (
    livro_codl    INT NOT NULL,
    assunto_codas INT NOT NULL,
    PRIMARY KEY (livro_codl, assunto_codas)
);
CREATE INDEX IDX_53C2C52AA53550D7 ON livro_assunto (livro_codl);    -- Livro_Assunto_FKIndex1
CREATE INDEX IDX_53C2C52A831BDC55 ON livro_assunto (assunto_codas); -- Livro_Assunto_FKIndex2
ALTER TABLE livro_assunto ADD CONSTRAINT FK_53C2C52AA53550D7
    FOREIGN KEY (livro_codl) REFERENCES livro (codl) ON DELETE CASCADE NOT DEFERRABLE;
ALTER TABLE livro_assunto ADD CONSTRAINT FK_53C2C52A831BDC55
    FOREIGN KEY (assunto_codas) REFERENCES assunto (codas) ON DELETE RESTRICT NOT DEFERRABLE;

-- -----------------------------------------------------------------------------
-- View do relatório: uma linha por (autor, livro).
-- Um livro com N autores aparece N vezes, uma em cada grupo; autores sem livro
-- aparecem com as colunas do livro nulas. Assuntos e coautores vêm agregados
-- com separador "|".
-- -----------------------------------------------------------------------------
CREATE VIEW vw_livros_por_autor AS
SELECT
    a.codau          AS autor_codau,
    a.nome           AS autor_nome,
    l.codl           AS livro_codl,
    l.titulo,
    l.editora,
    l.edicao,
    l.anopublicacao,
    l.valor,
    (
        SELECT string_agg(s.descricao, '|' ORDER BY s.descricao)
        FROM livro_assunto ls
        JOIN assunto s ON s.codas = ls.assunto_codas
        WHERE ls.livro_codl = l.codl
    )                AS assuntos,
    (
        SELECT string_agg(co.nome, '|' ORDER BY co.nome)
        FROM livro_autor lco
        JOIN autor co ON co.codau = lco.autor_codau
        WHERE lco.livro_codl = l.codl
          AND lco.autor_codau <> a.codau
    )                AS coautores
FROM autor a
LEFT JOIN livro_autor la ON la.autor_codau = a.codau
LEFT JOIN livro l ON l.codl = la.livro_codl;

COMMIT;
